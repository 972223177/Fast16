/**
 * 像素礼花（成功反馈：生成计划 / 日常打卡 / 三餐全打卡）。
 *
 * 预定义爆裂帧序列（字符网格，Y=黄 G=绿 R=红 B=蓝），PixelSprite 单次播放——
 * 帧间阶跃扩散（无插值、无平滑），播完回调 [onFinished] 由调用方移除。
 *
 * @param burst 礼花档位：日常打卡小礼花 / 全打卡多彩大礼花 / 生成计划成功礼花
 */
enum class PixelConfettiBurst { CHECK_IN, ALL_COMPLETED, PLAN_CREATED }

/** 礼花调色板：与 PixelColors 一致（Y 黄 / G 绿 / R 红 / B 蓝） */
private val CONFETTI_PALETTE = mapOf(
    'Y' to PixelColors.yellow,
    'G' to PixelColors.green,
    'R' to PixelColors.red,
    'B' to PixelColors.blue,
)

@Composable
fun PixelConfetti(
    burst: PixelConfettiBurst,
    onFinished: () -> Unit,
    modifier: Modifier = Modifier,
) {
    val frames = when (burst) {
        PixelConfettiBurst.CHECK_IN -> CONFETTI_CHECK_IN
        PixelConfettiBurst.ALL_COMPLETED -> CONFETTI_ALL_COMPLETED
        PixelConfettiBurst.PLAN_CREATED -> CONFETTI_PLAN_CREATED
    }
    var index by remember(burst) { mutableIntStateOf(0) }
    LaunchedEffect(burst) {
        // 轻微入场延迟后逐帧播放（阶跃扩散，最后回调移除）
        delay(PixelMotion.Pop.STEP_MS.milliseconds)
        for (i in frames.indices) {
            index = i
            delay(PixelMotion.FRAME_MS.milliseconds)
        }
        onFinished()
    }
    PixelSprite(
        rows = frames[index],
        palette = CONFETTI_PALETTE,
        modifier = modifier,
        contentDescription = "像素礼花",
    )
}

